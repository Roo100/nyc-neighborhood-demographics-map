#!/usr/bin/env python3
"""Build NTA income/poverty estimates from ACS 2024 5-year TRACT detailed tables.

Input: data/acs/tract_income_2024.csv, generated by fetch_acs_income.py.
Join:  data/tract_to_nta2020.csv (official NYC DCP hm78-6dwm).
Output is data for QA, not authorization to render/interpret an income choropleth.
"""
from collections import defaultdict
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CROSSWALK = ROOT / "data/tract_to_nta2020.csv"
TRACT_CSV = ROOT / "data/acs/tract_income_2024.csv"
OUTPUT = ROOT / "data/acs/nta_income_2024.json"
BRACKET_COLS = [f"B19001_{i:03d}E" for i in range(2, 18)]
FIELDS = ["B19001_001E", *BRACKET_COLS, "B17001_001E", "B17001_002E"]
BRACKET_LIMITS = [
    (0, 10000), (10000, 15000), (15000, 20000), (20000, 25000),
    (25000, 30000), (30000, 35000), (35000, 40000), (40000, 45000),
    (45000, 50000), (50000, 60000), (60000, 75000), (75000, 100000),
    (100000, 125000), (125000, 150000), (150000, 200000), (200000, None)
]


def as_count(value):
    """Return None for suppressed, missing or nonnumeric values; never replace with zero."""
    try:
        text = str(value).strip()
        count = int(text)
        return count if count >= 0 else None
    except (ValueError, TypeError):
        return None


def grouped_median(counts, household_total):
    """Interpolation within the ACS household-income band containing the 50th percentile.

    This is a *derived grouped-data approximation*, not the ACS B19013 median.
    """
    if not household_total or household_total < 0 or len(counts) != len(BRACKET_LIMITS):
        return None
    target = household_total / 2
    below = 0
    for count, (low, high) in zip(counts, BRACKET_LIMITS):
        if count < 0:
            return None
        if below + count >= target and count > 0:
            if high is None:
                return None  # Top income band is unbounded.
            return round(low + (target - below) / count * (high - low))
        below += count
    return None


def parse_crosswalk(path):
    pairs = {}
    with path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            tract = row.get("tract_geoid", "")
            nta = row.get("nta2020", "")
            if len(tract) != 11 or len(nta) != 6 or tract in pairs:
                raise ValueError(f"Invalid/duplicate tract assignment: {tract!r}")
            pairs[tract] = nta
    if len(pairs) < 2000:
        raise ValueError("Tract crosswalk is incomplete")
    return pairs


def aggregate(tract_rows, crosswalk, nta_codes):
    by_nta = defaultdict(list)
    tract_index = {}
    for row in tract_rows:
        geoid = str(row.get("tract_geoid") or "")
        if len(geoid) != 11 or not geoid.isdigit() or geoid in tract_index:
            raise ValueError(f"Invalid/duplicate ACS tract GEOID: {geoid!r}")
        tract_index[geoid] = row
    for geoid, nta in crosswalk.items():
        if nta not in nta_codes:
            raise ValueError(f"Unknown official NTA {nta!r}")
        by_nta[nta].append((geoid, tract_index.get(geoid)))
    result = []
    for nta in sorted(nta_codes):
        members = by_nta.get(nta, [])
        errors = []
        totals = [0] * len(FIELDS)
        if not members:
            errors.append("no crosswalk tracts")
        for geoid, row in members:
            if row is None:
                errors.append(f"missing ACS tract {geoid}")
                continue
            counts = [as_count(row.get(field)) for field in FIELDS]
            if any(v is None for v in counts):
                errors.append(f"missing/suppressed ACS variable in tract {geoid}")
                continue
            if sum(counts[1:17]) != counts[0]:
                errors.append(f"inconsistent income distribution total in tract {geoid}")
                continue
            if counts[18] > counts[17]:
                errors.append(f"poverty numerator exceeds denominator in tract {geoid}")
                continue
            totals = [v + n for v, n in zip(totals, counts)]
        if errors:
            result.append({"nta2020": nta, "status": "not_available", "reasons": errors,
                           "tracts_expected": len(members)})
            continue
        households = totals[0]
        bins = totals[1:17]
        poverty_universe = totals[17]
        poverty_below = totals[18]
        result.append({
            "nta2020": nta,
            "status": "derived_from_tract_acs",
            "tracts": len(members),
            "households": households,
            "income_bracket_households": dict(zip(BRACKET_COLS, bins)),
            "median_household_income_grouped_approx_usd": grouped_median(bins, households),
            "poverty_universe_people": poverty_universe,
            "below_poverty_people": poverty_below,
            "poverty_rate_pct": round(poverty_below / poverty_universe * 100, 2) if poverty_universe else None,
            "income_measure_type": "grouped-data interpolation; derived approximation (not published ACS median)",
            "income_currency": "2024 USD"
        })
    return result, sorted(set(tract_index) - set(crosswalk))


def main():
    for path in (CROSSWALK, TRACT_CSV):
        if not path.exists():
            raise SystemExit(f"Missing required input: {path.relative_to(ROOT)}")
    geography = json.loads((ROOT / "data/nta2020.geojson").read_text())
    nta_codes = {f["properties"]["nta2020"] for f in geography["features"]}
    if len(nta_codes) != 262:
        raise SystemExit("Cannot use incomplete geography")
    crosswalk = parse_crosswalk(CROSSWALK)
    with TRACT_CSV.open(newline="", encoding="utf-8") as handle:
        records, omitted = aggregate(list(csv.DictReader(handle)), crosswalk, nta_codes)
    qa_ready = sum(x["status"] == "derived_from_tract_acs" for x in records)
    output = {
        "dataset": "ACS 2020-2024 five-year detailed tables",
        "reference_geography": "2020 NYC NTA",
        "source": "U.S. Census Bureau; official DCP tract-to-NTA equivalency hm78-6dwm",
        "data_status": "QA ONLY - NOT APPROVED FOR MAP PUBLICATION",
        "n_nta": len(records),
        "n_nta_complete": qa_ready,
        "n_nta_missing_or_suppressed": len(records) - qa_ready,
        "acs_tracts_not_in_official_equivalency": omitted,
        "source_csv_sha256": hashlib.sha256(TRACT_CSV.read_bytes()).hexdigest(),
        "records": records
    }
    OUTPUT.write_text(json.dumps(output, separators=(",", ":")) + "\n", encoding="utf-8")
    print(json.dumps({key: value for key, value in output.items() if key != "records"}, indent=2))


if __name__ == "__main__":
    main()
